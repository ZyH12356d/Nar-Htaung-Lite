import { createHash } from 'node:crypto';
import { copyFile, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { dirname, isAbsolute, join, parse, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export async function prepareRelease({ root, env = process.env }) {
  root = resolve(root);
  if (root === parse(root).root) throw new Error('Use a project directory, not a filesystem root.');
  const config = JSON.parse(await readFile(join(root, 'release.config.json'), 'utf8'));
  const remoteUrl = env['APK_DOWNLOAD_URL']?.trim() || config.downloadUrl?.trim();
  const version = env['APP_VERSION']?.trim() || config.version;
  if (!version || !/^[\w.+-]+$/.test(version)) throw new Error('Set a valid app version.');
  const fileName = config.fileName || `nar-htaung-lite-${version}.apk`;
  if (!/^[\w.-]+\.apk$/.test(fileName)) throw new Error('The APK filename must be a simple .apk filename.');

  const generated = join(root, 'src/app/release.generated.ts');
  // Remove stale generated data before preparing a new artifact.
  await rm(generated, { force: true });
  const downloads = resolve(root, 'public/downloads');
  const outputPath = relative(root, downloads);
  if (!outputPath || outputPath.startsWith('..') || isAbsolute(outputPath))
    throw new Error('The generated downloads directory must stay inside the website project.');
  let downloadUrl, fileSizeBytes = config.fileSizeBytes, sha256 = config.sha256 || '';
  if (remoteUrl) {
    let url;
    try { url = new URL(remoteUrl); } catch { throw new Error('APK_DOWNLOAD_URL must be an absolute HTTPS APK URL.'); }
    if (url.protocol !== 'https:' || url.username || url.password || !url.pathname.toLowerCase().endsWith('.apk'))
      throw new Error('APK_DOWNLOAD_URL must be an absolute HTTPS APK URL without credentials.');
    downloadUrl = url.href;
    // These are this script's generated outputs, never user assets.
    await rm(downloads, { recursive: true, force: true });
  } else {
    if (env['VERCEL'] === '1')
      throw new Error('Set APK_DOWNLOAD_URL in Vercel to your public signed APK release URL before deploying.');
    const source = env['APK_SOURCE'] || resolve(root, '../MusicPlayer/bin/Release/net10.0-android/com.companyname.musicplayer-Signed.apk');
    let bytes;
    try { bytes = await readFile(source); }
    catch { throw new Error('No APK is configured. Build the Android Release APK locally, set APK_SOURCE, or set APK_DOWNLOAD_URL.'); }
    if (bytes.length < 4 || bytes[0] !== 0x50 || bytes[1] !== 0x4b)
      throw new Error('APK_SOURCE is not an APK/ZIP file.');
    fileSizeBytes = bytes.length;
    sha256 = createHash('sha256').update(bytes).digest('hex');
    await mkdir(downloads, { recursive: true });
    await copyFile(source, join(downloads, fileName));
    downloadUrl = `/downloads/${fileName}`;
  }
  if (fileSizeBytes !== null && (!Number.isSafeInteger(fileSizeBytes) || fileSizeBytes <= 0))
    throw new Error('fileSizeBytes must be a positive integer or null.');
  if (sha256 && !/^[a-f0-9]{64}$/i.test(sha256)) throw new Error('sha256 must contain 64 hexadecimal characters.');
  const release = {
    version, channel: config.channel || 'Beta',
    minimumAndroidVersion: config.minimumAndroidVersion,
    architecture: config.architecture,
    downloadUrl, fileName, fileSizeBytes, sha256,
  };
  await mkdir(dirname(generated), { recursive: true });
  await writeFile(generated, '// Generated by scripts/prepare-release.mjs. Edit release.config.json instead.\nexport const release = ' + JSON.stringify(release, null, 2) + ' as const;\n');
  await writeFile(join(root, 'public/release.json'), JSON.stringify(release, null, 2) + '\n');
  return release;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
    const release = await prepareRelease({ root });
    console.log(`Prepared Nar Htaung Lite ${release.version} (${release.downloadUrl.startsWith('/') ? 'local APK' : 'public release'}).`);
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
